def build_region_dimension(infectious: pd.DataFrame) -> pd.DataFrame:
    log("Building region dimension")
    regions = infectious[["kraj_kod", "kraj_nazev"]].drop_duplicates().copy()
    regions["region_code"] = regions["kraj_kod"].astype("string")
    regions["region_name_cs"] = regions["kraj_nazev"].astype("string")
    return regions[["region_code", "region_name_cs"]]


def build_final_fact(infectious: pd.DataFrame, dim_mkn: pd.DataFrame, dim_age: pd.DataFrame) -> pd.DataFrame:
    log("Building final enriched infectious-disease fact table")
    fact = infectious.copy()
    fact.insert(0, "source_row_id", range(1, len(fact) + 1))
    fact["fact_id"] = fact["source_row_id"]
    fact["source_dataset"] = "infectious_diseases"
    fact["report_year"] = pd.to_numeric(fact["rok"], errors="coerce").astype("Int64")
    fact["report_month"] = pd.to_numeric(fact["mesic"], errors="coerce").astype("Int64")
    fact["period_yyyymm"] = fact["report_year"] * 100 + fact["report_month"]
    fact["date_grain"] = "month"
    fact["region_code"] = fact["kraj_kod"].astype("string")
    fact["region_name_cs"] = fact["kraj_nazev"].astype("string")
    fact["diagnosis_code"] = fact["diagnoza"].astype("string")
    fact["diagnosis_name_cs"] = fact["diagnoza_nazev"].astype("string")
    fact["age_group_code"] = fact["vek_kod"].astype("string")
    fact["age_group_name_cs"] = fact["vek_nazev"].astype("string")
    fact["sex_code"] = fact["pohlavi"].astype("string")
    fact["sex_name_cs"] = fact["sex_code"].map(SEX_LABELS_CS).astype("string")
    fact["ews_code"] = pd.to_numeric(fact["EWS"], errors="coerce").astype("Int64")
    fact["reported_case_count"] = pd.to_numeric(fact["pocet_pripadu"], errors="coerce").fillna(0).astype("int64")

    fact = fact.merge(dim_mkn, left_on="diagnosis_code", right_on="mkn_code", how="left")
    fact = fact.merge(dim_age, on="age_group_code", how="left", suffixes=("", "_official"))
    fact["has_mkn_match"] = fact["mkn_code"].notna()
    fact["has_age_group_match"] = fact["age_from_inclusive"].notna()

    ordered_columns = [column["column"] for column in FINAL_TABLE_COLUMNS]
    return fact[ordered_columns]


def load_kg_nodes() -> pd.DataFrame:
    path = KG_DIR / "nodes.jsonl"
    if not path.exists():
        return pd.DataFrame(columns=["node_id", "node_type", "node_label", "aliases_json", "properties_json"])
    rows = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            record = json.loads(line)
            rows.append(
                {
                    "node_id": record.get("id"),
                    "node_type": record.get("type"),
                    "node_label": record.get("label"),
                    "aliases_json": json.dumps(record.get("aliases", []), ensure_ascii=False),
                    "properties_json": json.dumps(record.get("properties", {}), ensure_ascii=False),
                }
            )
    return pd.DataFrame(rows)


