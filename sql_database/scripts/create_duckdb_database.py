def create_views_and_indexes(con: duckdb.DuckDBPyConnection) -> None:
    log("Creating compatibility view and indexes")
    con.execute(
        f"""
        CREATE OR REPLACE VIEW infectious_diseases AS
        SELECT
          report_year AS rok,
          report_month AS mesic,
          region_code AS kraj_kod,
          region_name_cs AS kraj_nazev,
          diagnosis_code AS diagnoza,
          diagnosis_name_cs AS diagnoza_nazev,
          age_group_code AS vek_kod,
          age_group_name_cs AS vek_nazev,
          sex_code AS pohlavi,
          ews_code AS EWS,
          reported_case_count AS pocet_pripadu
        FROM {FINAL_TABLE_NAME}
        """
    )
    for statement in [
        f"CREATE INDEX IF NOT EXISTS idx_fact_diag ON {FINAL_TABLE_NAME}(diagnosis_code)",
        f"CREATE INDEX IF NOT EXISTS idx_fact_block ON {FINAL_TABLE_NAME}(mkn_block_code)",
        f"CREATE INDEX IF NOT EXISTS idx_fact_year ON {FINAL_TABLE_NAME}(report_year)",
        f"CREATE INDEX IF NOT EXISTS idx_fact_region ON {FINAL_TABLE_NAME}(region_code)",
        f"CREATE INDEX IF NOT EXISTS idx_fact_age ON {FINAL_TABLE_NAME}(age_group_code)",
        f"CREATE INDEX IF NOT EXISTS idx_fact_block_year ON {FINAL_TABLE_NAME}(mkn_block_code, report_year)",
        f"CREATE INDEX IF NOT EXISTS idx_fact_diag_region ON {FINAL_TABLE_NAME}(diagnosis_code, region_code)",
    ]:
        con.execute(statement)
    con.execute("ANALYZE")


def create_database(db_path: Path, *, overwrite: bool) -> dict[str, Any]:
    db_path.parent.mkdir(parents=True, exist_ok=True)
    if db_path.exists() and overwrite:
        db_path.unlink()
    elif db_path.exists() and not overwrite:
        raise FileExistsError(f"{db_path} already exists; pass --overwrite to rebuild it.")

    data = read_csvs()
    dim_block = build_block_dimension()
    dim_mkn = build_mkn_dimension(data["mkn10"])
    dim_age = build_age_dimension(data["age_groups"])
    dim_region = build_region_dimension(data["infectious"])
    fact = build_final_fact(data["infectious"], dim_mkn, dim_age)
    kg_nodes = load_kg_nodes()
    kg_edges = load_kg_edges()
    eval_tables = load_evaluation_tables()
    write_docs(fact)

    log(f"Writing DuckDB database to {db_path.relative_to(ROOT)}")
    con = duckdb.connect(str(db_path))
    con.execute(f"PRAGMA threads={max(1, os.cpu_count() or 1)}")

    register_table(con, "source_infectious_diseases", data["infectious"])
    register_table(con, "source_age_groups", data["age_groups"])
    register_table(con, "source_mkn10_cz", data["mkn10"])
    register_table(con, "source_hospitalization", data["hospitalization"])
    register_table(con, "dim_mkn10_block", dim_block)
    register_table(con, "dim_mkn10_code", dim_mkn)
    register_table(con, "dim_age_group", dim_age)
    register_table(con, "dim_region", dim_region)
    register_final_fact_table(con, fact)
    register_table(con, "kg_node", kg_nodes)
    register_table(con, "kg_edge", kg_edges)
    register_table(con, "column_dictionary", pd.DataFrame(FINAL_TABLE_COLUMNS))
    for name, frame in eval_tables.items():
        register_table(con, name, frame)
    create_views_and_indexes(con)

    table_counts = {}
    for table_name in [
        "source_infectious_diseases",
        "source_age_groups",
        "source_mkn10_cz",
        "source_hospitalization",
        "dim_mkn10_block",
        "dim_mkn10_code",
        "dim_age_group",
        "dim_region",
        FINAL_TABLE_NAME,
        "kg_node",
        "kg_edge",
        "evaluation_question",
    ]:
        table_counts[table_name] = int(con.execute(f"SELECT COUNT(*) FROM {table_name}").fetchone()[0])
    con.close()

    manifest = {
        "generated_at": now_iso(),
        "database_path": str(db_path.relative_to(ROOT)),
        "database_bytes": db_path.stat().st_size,
        "duckdb_version": duckdb.__version__,
        "final_table": FINAL_TABLE_NAME,
        "final_table_rows": int(len(fact)),
        "final_table_columns": len(FINAL_TABLE_COLUMNS),
        "table_counts": table_counts,
        "source_files": {
            "infectious_diseases": {
                "path": "data/raw/infectious_diseases.csv",
                "sha256": file_sha256(RAW_DIR / "infectious_diseases.csv"),
            },
            "age_groups": {
                "path": "data/raw/age_groups.csv",
                "sha256": file_sha256(RAW_DIR / "age_groups.csv"),
            },
            "mkn10_cz": {
                "path": "data/raw/mkn10_cz.csv",
                "sha256": file_sha256(RAW_DIR / "mkn10_cz.csv"),
            },
            "hospitalization": {
                "path": "data/raw/hospitalization.csv",
                "sha256": file_sha256(RAW_DIR / "hospitalization.csv"),
            },
        },
        "notes": [
            "The final answer table is fact_infectious_disease_cases_enriched.",
            "Both standard RAG and KG-RAG should generate SQL against the same final table.",
            "KG-RAG's expected advantage is better scope construction before SQL, not a different fact table.",
        ],
    }
    (SQL_ROOT / "db_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description="Create the local DuckDB database for SQL answer generation.")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB_PATH)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    manifest = create_database(args.db, overwrite=args.overwrite)
    print(
        f"Created {manifest['database_path']} with final table "
        f"{manifest['final_table']} ({manifest['final_table_rows']} rows)."
    )
    return 0


