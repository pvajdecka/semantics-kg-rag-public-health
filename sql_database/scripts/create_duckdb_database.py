def load_evaluation_tables() -> dict[str, pd.DataFrame]:
    path = OUTPUTS_DIR / "kg_rag_evaluation_queries.json"
    if not path.exists():
        return {
            "evaluation_question": pd.DataFrame(),
            "evaluation_scope_diagnosis_code": pd.DataFrame(),
            "evaluation_scope_absent_mkn_code": pd.DataFrame(),
            "evaluation_scope_age_group": pd.DataFrame(),
            "evaluation_scope_region": pd.DataFrame(),
            "evaluation_scope_year": pd.DataFrame(),
        }
    records = json.loads(path.read_text(encoding="utf-8"))
    question_rows = []
    diagnosis_rows = []
    absent_rows = []
    age_rows = []
    region_rows = []
    year_rows = []
    for item in records:
        qid = item["id"]
        scope = item.get("gold_scope") or {}
        question_rows.append(
            {
                "evaluation_id": qid,
                "query_cs": item.get("query_cs"),
                "query_en": item.get("query_en"),
                "intent": item.get("intent"),
                "primary_metric": item.get("primary_metric"),
                "expected_sql_shape": item.get("expected_sql_shape"),
                "mkn_group": scope.get("mkn_group"),
            }
        )
        for code in scope.get("diagnosis_codes", []):
            diagnosis_rows.append({"evaluation_id": qid, "diagnosis_code": code})
        for code in scope.get("mkn_relevant_absent_codes", []):
            absent_rows.append({"evaluation_id": qid, "mkn_code": code})
        for code in scope.get("age_groups", []):
            age_rows.append({"evaluation_id": qid, "age_group_code": str(code)})
        for region in scope.get("regions", []):
            region_rows.append({"evaluation_id": qid, "region_name_cs": region})
        if scope.get("region_code") or scope.get("region_label"):
            region_rows.append(
                {
                    "evaluation_id": qid,
                    "region_code": scope.get("region_code"),
                    "region_name_cs": scope.get("region_label"),
                }
            )
        for year in scope.get("years", []):
            year_rows.append({"evaluation_id": qid, "report_year": int(year)})
    return {
        "evaluation_question": pd.DataFrame(question_rows),
        "evaluation_scope_diagnosis_code": pd.DataFrame(diagnosis_rows),
        "evaluation_scope_absent_mkn_code": pd.DataFrame(absent_rows),
        "evaluation_scope_age_group": pd.DataFrame(age_rows),
        "evaluation_scope_region": pd.DataFrame(region_rows),
        "evaluation_scope_year": pd.DataFrame(year_rows),
    }


def write_docs(final_table: pd.DataFrame) -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    (DOCS_DIR / "final_table_columns.json").write_text(
        json.dumps(FINAL_TABLE_COLUMNS, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    pd.DataFrame(FINAL_TABLE_COLUMNS).to_csv(DOCS_DIR / "final_table_columns.csv", index=False, encoding="utf-8")
    summary = {
        "table": FINAL_TABLE_NAME,
        "row_count": int(len(final_table)),
        "column_count": int(len(final_table.columns)),
        "sum_reported_case_count": int(final_table["reported_case_count"].sum()),
        "diagnosis_count": int(final_table["diagnosis_code"].nunique()),
        "region_count": int(final_table["region_code"].nunique()),
        "age_group_count": int(final_table["age_group_code"].nunique()),
        "year_min": int(final_table["report_year"].min()),
        "year_max": int(final_table["report_year"].max()),
    }
    (DOCS_DIR / "final_table_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def register_table(con: duckdb.DuckDBPyConnection, name: str, frame: pd.DataFrame) -> None:
    con.register(f"df_{name}", frame)
    con.execute(f"CREATE OR REPLACE TABLE {name} AS SELECT * FROM df_{name}")
    con.unregister(f"df_{name}")


