def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def log(message: str) -> None:
    print(f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')} UTC] {message}", flush=True)


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def code_rank(code: str) -> int | None:
    code = str(code).strip().upper()
    if len(code) < 3 or not code[0].isalpha() or not code[1:3].isdigit():
        return None
    return (ord(code[0]) - ord("A")) * 1000 + int(code[1:3])


def block_for_code(code: str) -> tuple[str, str, str] | None:
    rank = code_rank(code)
    if rank is None:
        return None
    for start, end, label in DERIVED_MKN_BLOCKS:
        start_rank = code_rank(start)
        end_rank = code_rank(end)
        if start_rank is not None and end_rank is not None and start_rank <= rank <= end_rank:
            return f"{start}-{end}", label, BLOCK_SOURCE
    return None


