def build_block_dimension() -> pd.DataFrame:
    rows = []
    for start, end, label in DERIVED_MKN_BLOCKS:
        rows.append(
            {
                "mkn_block_code": f"{start}-{end}",
                "mkn_block_start_code": start,
                "mkn_block_end_code": end,
                "mkn_block_start_rank": code_rank(start),
                "mkn_block_end_rank": code_rank(end),
                "mkn_block_name_cs": label,
                "mkn_block_source": BLOCK_SOURCE,
            }
        )
    return pd.DataFrame(rows)


def build_mkn_dimension(mkn10: pd.DataFrame) -> pd.DataFrame:
    log("Building enriched MKN-10-CZ dimension")
    mkn = mkn10.drop_duplicates("kod").copy()
    block_records = mkn["kod"].map(lambda value: block_for_code(str(value)))
    return pd.DataFrame(
        {
            "mkn_code": mkn["kod"].astype("string"),
            "mkn_code_with_dot": mkn["kod_tecka"].astype("string"),
            "mkn_name_cs": mkn["nazev"].astype("string"),
            "mkn_iri": mkn["kod_IRI"].astype("string"),
            "mkn_chapter_range": mkn["kod_kapitola_rozsah"].astype("string"),
            "mkn_chapter_number": mkn["kod_kapitola_cislo"].astype("string"),
            "mkn_chapter_name_cs": mkn["nazev_kapitola"].astype("string"),
            "mkn_valid_from": mkn["platnost_od"].astype("string"),
            "mkn_valid_to": mkn["platnost_do"].astype("string"),
            "mkn_block_code": block_records.map(lambda item: item[0] if item else None).astype("string"),
            "mkn_block_name_cs": block_records.map(lambda item: item[1] if item else None).astype("string"),
            "mkn_block_source": block_records.map(lambda item: item[2] if item else None).astype("string"),
        }
    )


